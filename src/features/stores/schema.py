"""SQLite schema generated from the data dictionaries (E3 child a, change 015).

    .venv\\Scripts\\python -m src.features.stores.schema     # writes schema.sql

Two dictionaries in one Markdown table format: the generator's (41 published files) and
`reconciled_dictionary.md` (6 reconciled files). Rules (015 plan, AC-2):
- id -> TEXT; `primary key` -> PRIMARY KEY, else a composite PRIMARY KEY over the id columns
- a value naming exactly one `x.csv` (and no `by`) -> FOREIGN KEY to x's primary key
- a value naming two files `by` a column -> no FOREIGN KEY (checked by tests)
- enum -> TEXT CHECK (IN values); int -> INTEGER; decimal -> REAL; date, text -> TEXT
- NOT NULL unless the values mention `blank` or `unmapped`
"""
import re
from dataclasses import dataclass, field
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
DICTIONARIES = (ROOT / "src" / "features" / "generator" / "README.md", HERE / "reconciled_dictionary.md")
SCHEMA = HERE / "schema.sql"
SQL_TYPE = {"int": "INTEGER", "decimal": "REAL"}
SECTION = re.compile(r"^### `([^`]+)\.csv`\n\n\| column \| type \| values \|\n\|---\|---\|---\|\n((?:\|.*\n?)+)", re.M)


@dataclass
class Column:
    name: str
    type: str
    values: str

    @property
    def primary(self) -> bool:
        return "primary key" in self.values

    @property
    def nullable(self) -> bool:
        return "blank" in self.values or "unmapped" in self.values

    @property
    def references(self) -> str | None:
        files = re.findall(r"`([a-z_]+)\.csv`", self.values)
        return files[0] if len(files) == 1 and " by " not in self.values else None

    @property
    def enum_values(self) -> list[str]:
        return [v.strip() for v in self.values.split(",")] if self.type == "enum" else []


@dataclass
class Table:
    name: str           # table name, e.g. risk_erm or canonical_risk
    path: str           # CSV path relative to the build, e.g. reconciled/canonical_risk.csv
    columns: list[Column] = field(default_factory=list)

    @property
    def primary_key(self) -> list[str]:
        explicit = [c.name for c in self.columns if c.primary]
        return explicit or [c.name for c in self.columns if c.type == "id"]


def parse(text: str) -> list[Table]:
    """Every dictionary section except the answer key's."""
    tables = []
    for match in SECTION.finditer(text):
        path = match.group(1) + ".csv"
        if path.startswith("answer_key/"):
            continue
        cells = [[c.strip() for c in line.strip().strip("|").split("|")] for line in match.group(2).strip().splitlines()]
        tables.append(Table(path.split("/")[-1][:-4], path, [Column(c[0].strip("`"), c[1], c[2]) for c in cells]))
    return tables


def load_tables(dictionaries=DICTIONARIES) -> list[Table]:
    """All tables, in foreign-key dependency order (referenced tables first, then by name)."""
    tables = {t.name: t for d in dictionaries for t in parse(Path(d).read_text(encoding="utf-8"))}
    ordered, done = [], set()
    while len(ordered) < len(tables):
        ready = sorted(n for n, t in tables.items() if n not in done
                       and all(c.references in done or c.references == n for c in t.columns if c.references))
        if not ready:
            raise ValueError(f"foreign-key cycle among {sorted(set(tables) - done)}")
        for n in ready:
            ordered.append(tables[n])
            done.add(n)
    return ordered


def ddl(table: Table, tables: dict[str, Table]) -> str:
    lines = []
    single_pk = table.primary_key if len(table.primary_key) == 1 and any(c.primary for c in table.columns) else []
    for c in table.columns:
        line = f"  {c.name} {SQL_TYPE.get(c.type, 'TEXT')}"
        if not c.nullable:
            line += " NOT NULL"
        if c.name in single_pk:
            line += " PRIMARY KEY"
        if c.enum_values:
            options = ", ".join("'" + v.replace("'", "''") + "'" for v in c.enum_values)
            line += f" CHECK ({c.name} IN ({options}))"
        lines.append(line)
    if not single_pk:
        lines.append(f"  PRIMARY KEY ({', '.join(table.primary_key)})")
    for c in table.columns:
        if c.references:
            target = tables[c.references]
            lines.append(f"  FOREIGN KEY ({c.name}) REFERENCES {target.name}({target.primary_key[0]})")
    return f"CREATE TABLE {table.name} (\n" + ",\n".join(lines) + "\n);"


def generate(dictionaries=DICTIONARIES) -> str:
    tables = load_tables(dictionaries)
    by_name = {t.name: t for t in tables}
    header = ("-- Generated by `python -m src.features.stores.schema` from the data dictionaries; do not edit.\n"
              "-- Tables are in foreign-key dependency order.\n\n")
    return header + "\n\n".join(ddl(t, by_name) for t in tables) + "\n"


def main() -> int:
    SCHEMA.write_text(generate(), encoding="utf-8", newline="\n")
    print(f"wrote {SCHEMA}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
