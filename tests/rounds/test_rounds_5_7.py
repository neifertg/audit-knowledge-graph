def sqlite_answers(out: Path, rounds=NEW, **kwargs) -> dict:
    con = R.sqlite_connection(out)
    try:
        return {r.number: R.run_sqlite(r, con, **kwargs) for r in rounds}
    finally:
        con.close()


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def temp_table_exists(con) -> bool:
    return bool(con.execute("SELECT count(*) FROM temp.sqlite_master WHERE name = 'vendor_relies_on'").fetchone()[0])


