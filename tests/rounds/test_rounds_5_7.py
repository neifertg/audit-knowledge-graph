    def test_ac2_sqlite_answers_match_oracle_and_scenarios(self):
        out, _ = loaded()
        got, orc = sqlite_answers(out), O.answers(out)
        for r in NEW:
            with self.subTest(round=r.number):
                self.assertTrue(same(r, got[r.number], orc[r.number]), f"{r.number} differs from the oracle")
        con = R.sqlite_connection(out)
        try:
            for r in NEW:
                if not r.has_setup:
                    self.assertEqual(tuple(d[0] for d in con.execute(r.sql, r.params).description), r.columns)
            # round 5 discriminates: direct and fourth-party-only rows; the direct-only baseline (an empty
            # register) marks every entity direct, so the fourth-party rows are exactly the new ones
            baseline = R.run_sqlite(BY[5], con, register=[])
        finally:
            con.close()
        kinds = defaultdict(set)
        for entity, exposure in got[5]:
            kinds[exposure].add(entity)
        self.assertTrue(kinds["direct"] and kinds["fourth_party_only"], kinds)
        self.assertEqual({e for e, _ in baseline}, kinds["direct"])
        self.assertEqual({x for _, x in baseline}, {"direct"})
        self.assertTrue(same(BY[5], baseline, O.answers(out, vendor=BY[5].params["vendor"], register=[])[5]))
        scenarios = defaultdict(set)
        for row in answer_key(out, "scenarios"):
            scenarios[row["scenario"]].add(row["item_id"])
        # round 6: exactly the planted repeat-finding groups, titles pairwise different
        groups, titles = defaultdict(set), defaultdict(list)
        for control, issue, _, title in got[6]:
            groups[control].add(issue)
            titles[control].append(title)
        planted = {frozenset(v) for k, v in scenarios.items() if k.startswith("repeat_finding:")}
        self.assertTrue(planted)
        self.assertEqual({frozenset(g) for g in groups.values()}, planted)
        for control, ts in titles.items():
            self.assertEqual(len(ts), len(set(ts)), control)
        # round 7: the top riser is the planted rising category and meets E1's thresholds
        riser = O.top_riser(got[7])
        self.assertEqual({riser["l1_node_id"]}, scenarios["rising_category"])
        self.assertGreaterEqual(riser["2023"], 8)
        self.assertGreaterEqual(riser["2025"], 1.5 * riser["2023"])
        totals = defaultdict(int)
        for _, _, year, n in got[7]:
            totals[str(year)] += n
        self.assertLessEqual(abs(totals["2025"] - totals["2023"]), 0.15 * totals["2023"])
        # owner concentration: ordered by key controls, then units, descending, then person ID
        owners = got["owners"]
        self.assertEqual(owners, sorted(owners, key=lambda t: (-t[1], -t[2], t[0])))
        self.assertEqual(len(owners), 10)
        print(f"\n[018 AC-2] seed 42: round 5 {len(got[5])} entities ({len(kinds['direct'])} direct, "
              f"{len(kinds['fourth_party_only'])} fourth-party only) for {BY[5].params['vendor']}; round 6 "
              f"{len(groups)} controls, {len(got[6])} issues; round 7 {len(got[7])} rows, riser {riser}; "
              f"owners top {owners[:2]}")

    def test_ac3_agreement_and_round5_isolation(self):
        driver, out = graph()
        results = R.run_rounds(out, driver, NEW)
        for res in results:
            with self.subTest(round=res.round.number):
                self.assertTrue(res.agree, f"{res.round.number}: SQL and Cypher differ")
                if not res.round.has_setup:
                    keys = driver.execute_query(res.round.cypher, res.round.params).keys
                    self.assertEqual(tuple(keys), res.round.columns)
        db = out / DATABASE
        before_graph, before_db = snapshot(driver), sha256(db)
        vendors = lambda: driver.execute_query("MATCH (v:Vendor) RETURN count(v) AS n").records[0]["n"]
        con = R.sqlite_connection(out)
        try:
            R.run_sqlite(BY[5], con)
            R.run_neo4j(BY[5], driver)
            self.assertFalse(temp_table_exists(con))
            # a failing round 5 still rolls back on each engine
            with self.assertRaises(sqlite3.OperationalError):
                R.run_sqlite(BY[5], con, query="SELECT * FROM no_such_table")
            self.assertFalse(temp_table_exists(con))
            with self.assertRaises(Exception) as caught:
                R.run_neo4j(BY[5], driver, query="RETURN no_such_variable")
            self.assertEqual(type(caught.exception).__module__.split(".")[0], "neo4j")
        finally:
            con.close()
        self.assertEqual(vendors(), 0)
        self.assertEqual(sha256(db), before_db)
        self.assertEqual(snapshot(driver), before_graph, "round 5 left data behind in Neo4j")

