    def test_ac5_symmetric_verdict_rule(self):
        m = V.metrics
        self.assertEqual(m("SELECT a.x\nFROM a\nJOIN b ON b.id = a.id", "sql"), {"clauses": 2, "steps": 1, "moving_parts": 0})
        self.assertEqual(m("SELECT a.x\nFROM a\nLEFT JOIN b ON b.id = a.id", "sql")["clauses"], 2)
        cy = lambda pattern: m(f"MATCH (a){pattern}(b)\nRETURN b", "cypher")
        self.assertEqual(cy("-[:R*]->"), {"clauses": 2, "steps": 1, "moving_parts": 1})
        self.assertEqual(cy("-[:R*2]->"), {"clauses": 2, "steps": 2, "moving_parts": 0})
        self.assertEqual(cy("-[:R*1..3]->"), {"clauses": 2, "steps": 3, "moving_parts": 0})
        self.assertEqual(cy("-[:R*..3]->"), {"clauses": 2, "steps": 3, "moving_parts": 0})
        self.assertEqual(cy("-[:R*0..]->"), {"clauses": 2, "steps": 1, "moving_parts": 1})
        self.assertEqual(m("MATCH (a)\nRETURN [x IN a.l | x * 2] AS y", "cypher"), {"clauses": 2, "steps": 0, "moving_parts": 0})
        self.assertEqual(m("MATCH (a)-->(b)\nRETURN count(*) AS n", "cypher"), {"clauses": 2, "steps": 1, "moving_parts": 0})
        self.assertEqual(m("OPTIONAL MATCH (a)\nRETURN a", "cypher")["clauses"], 2)
        recursive = ("WITH RECURSIVE t(n) AS (\n  SELECT 1\n  UNION ALL\n  SELECT n + 1\n  FROM t\n  WHERE n < 5)\n"
                     "SELECT n\nFROM t")
        plain = "WITH x AS (\n  SELECT a.id\n  FROM a)\nSELECT x.id\nFROM x"
        self.assertEqual(m(recursive, "sql")["moving_parts"], 1)
        self.assertEqual(m(plain, "sql")["moving_parts"], 1)
        # a round with setup is scored as one text, setup first
        five = BY[5]
        self.assertTrue(five.scored("sql").startswith(five.sql_setup))
        self.assertTrue(five.scored("cypher").startswith(five.cypher_setup))
        self.assertEqual(m(five.scored("sql"), "sql"), {"clauses": 9, "steps": 5, "moving_parts": 3})
        self.assertEqual(m(five.scored("cypher"), "cypher"), {"clauses": 5, "steps": 6, "moving_parts": 6})  # 020
        # every round under the symmetric rule (SQL vs Cypher, verdict, margin)
        expected = {1: (9, 7, "graph", 0.25), 2: (21, 21, "close", -5.25), 3: (8, 7, "close", -0.75),
                    4: (7, 7, "close", -1.75), 5: (29, 41, "SQL", 4.75), 6: (17, 12, "graph", 2.0),
                    7: (10, 8, "graph", 0.0), "owners": (10, 9, "close", -1.25)}
        for r in ALL:
            a, b = m(r.scored("sql"), "sql"), m(r.scored("cypher"), "cypher")
            self.assertEqual((V.score(a), V.score(b), V.measured(a, b), V.margin(a, b)), expected[r.number], r.number)

    def test_ac3_020_published_rule_text(self):
        """020 AC-1 and AC-3: writes count once on both sides, the layout check keeps them, and the
        published rule text names the disclosed exceptions."""
        m = V.metrics
        sql = "CREATE TEMP TABLE t (v TEXT);\nINSERT INTO t (v)\nVALUES (:v)"
        cypher = "UNWIND $rows AS row\nMERGE (t:T {v: row.v})\nCREATE (t)-[:R]->(t)"
        self.assertEqual(m(sql, "sql"), {"clauses": 0, "steps": 0, "moving_parts": 2})
        self.assertEqual(m(cypher, "cypher"), {"clauses": 1, "steps": 1, "moving_parts": 2})  # UNWIND is the clause
        # each write adds exactly one moving part and no clause on its side
        # (UPDATE, not DELETE FROM: SQL's FROM is a keyword it writes, so it would add a clause as written)
        for engine, base, plus in (("sql", "INSERT INTO t (v)\nVALUES (:v)", "\nUPDATE t SET n = 1"),
                                   ("cypher", "MERGE (t:T {v: $v})", "\nSET t.n = 1")):
            a, b = m(base, engine), m(base + plus, engine)
            self.assertEqual((b["clauses"] - a["clauses"], b["moving_parts"] - a["moving_parts"]), (0, 1), engine)
        # the layout check still sees writes: MERGE and SET on one line are two clause keywords
        self.assertEqual(V.clauses_per_line("MERGE (t:T {v: $v}) SET t.n = 1", "cypher"), [2])
        counting = " ".join(E.RULE["counting"])
        self.assertIn("writes count once on both sides", counting)
        self.assertIn("filtering after an aggregate", counting)
        self.assertIn("HAVING", counting)
        self.assertIn("upserts", counting)
        self.assertIn("OPTIONAL MATCH is a clause", counting)

    def test_ac4_020_symmetry_table(self):
        """020 and 021: the published symmetry table. The expected figures are literals here (L-021);
        the snippets live in src/features/rounds/symmetry.py, and both the module's live table and the
        committed site.json must equal these literals."""
        from src.features.rounds import symmetry
        from src.features.site import export as site_export
        expected = {  # construct: (SQL clauses, steps, moving parts), (Cypher ...), disclosed
            "read": ((3, 0, 0), (3, 0, 0), False),
            "join or hop": ((2, 1, 0), (2, 1, 0), False),
            "fixed path *2": ((2, 2, 0), (2, 2, 0), False),
            "recursion (anchored on a literal)": ((7, 2, 1), (2, 1, 1), False),
            "recursion (anchored on a table)": ((8, 3, 1), (2, 1, 1), False),
            "stage": ((5, 1, 1), (3, 0, 1), False),
            "subquery": ((5, 1, 1), (4, 1, 1), False),
            "union": ((5, 1, 1), (5, 0, 1), False),
            "write": ((0, 0, 1), (0, 0, 1), False),
            "setup": ((0, 0, 2), (1, 1, 2), False),
            "optional": ((2, 1, 0), (3, 1, 0), False),
            "filter after an aggregate": ((4, 0, 0), (4, 0, 1), True),
            "upsert": ((0, 0, 2), (1, 0, 4), True),
            "select inside a write": ((2, 0, 1), (1, 0, 1), False),
        }
        self.assertEqual(set(symmetry.SNIPPETS), set(expected), "construct names match in both directions")
        as_literals = lambda rows: {r["construct"]: (tuple(r["sql_metrics"]), tuple(r["cypher_metrics"]), r["disclosed"])
                                    for r in rows}
        self.assertEqual(as_literals(symmetry.table()), expected, "symmetry.py's live table")
        committed = json.loads(site_export.SITE_JSON.read_text(encoding="utf-8"))["symmetry"]
        self.assertEqual(as_literals(committed), expected, "the committed site.json table")
        for name, (sql, cypher, disclosed) in expected.items():
            if not disclosed:
                self.assertEqual(sql[2], cypher[2], f"{name}: moving parts follow one rule")

